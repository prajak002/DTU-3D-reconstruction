"""LaTeX fragments, statistics and page numbers of the matched-patch protocol (run family P11-matched; Gates 6 and 7),
generated from the run CSVs so that no number is typed by hand.

  python scripts/make_tab_matched.py [--out paper/tex]   writes tab_matched.tex (the five native models),
                                                          tab_matched_heads.tex (heads, controls, probes),
                                                          results/P11-matched-stats.md, docs/assets/matched.json

Cells are pooled over the blur and noise fills, both seeds and the three evidence settings (gray is reported in the
stats file); means are means over scene means with 95% cluster-bootstrap intervals over scenes; paired tests are
sign-flip permutation tests on per-scene means. Columns: AUROC and CUR of U against the clean supported pixels (the
benchmark's original score), AUROC_m and CUR_m of U against the filled-but-observed pixels (same patch, same fill:
the matched score), the patch reaction AUROC_patch (clean S against filled-but-observed), and AUROC_m per evidence
bucket (one clean view at low parallax, one at high parallax, two, three or more)."""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASETS = [("DTU", "dtu", "P11-matched"), ("CO3Dv2", "co3d", "P11-matched-co3d")]
NATIVE = [("vggt", "VGGT-1B"), ("pi3", "Pi3"), ("pi3x", "Pi3X"), ("mapanything", "MapAnything"), ("da3", "Depth Anything 3")]
BASES = [("vggt", "VGGT-1B"), ("pi3x", "Pi3X"), ("pi3", "Pi3"), ("da3", "Depth Anything 3")]
HEAD_ROWS = [("", "native confidence"), ("_reproj", "reprojection, own cameras"),
             ("_oiavisself", "support head, label-free (clean-view labels)"),
             ("_oiamatchpatch", "matched per-image control (pipeline check)"), ("_oiamatchlin", "matched linear probe"),
             ("_oiamatch", "matched head, GT placement"), ("_oiamatchselfpatch", "matched per-image control, label-free"),
             ("_oiamatchself", "\\textbf{matched head, label-free}")]
COLS = ["auroc", "cur", "auroc_m", "cur_m", "auroc_patch", "auroc_m_ev1lo", "auroc_m_ev1hi", "auroc_m_ev2", "auroc_m_ev3p"]


def load(run):
    p = os.path.join(ROOT, "results", run, f"{run}.csv")
    if not os.path.exists(p):
        return None
    d = pd.read_csv(p)
    if "skipped" in d:
        d = d[~d.skipped.astype(bool)]
    return d.drop_duplicates(subset=["model", "scan", "seed", "radius_frac", "fill"])


def pooled(d, fills=("blur", "noise")):
    return d[d.fill_kind.isin(fills)]


def cell(d, model):
    x = d[d.model == model]
    if x.empty:
        return None
    out = {}
    for c in COLS:
        if c in x and x[c].notna().any():
            m, lo, hi, n = H.cluster_bootstrap_ci(x, c)
            out[c] = [round(m, 4), round(lo, 4), round(hi, 4), n]
        else:
            out[c] = None
    return out


def fmt(v, nd=3):
    return "--" if v is None else f"{v[0]:.{nd}f}"


def fmt_ci(v, nd=3):
    return "--" if v is None else f"{v[0]:.{nd}f} [{v[1]:.{nd}f}, {v[2]:.{nd}f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    data = {tag: load(run) for _, tag, run in DATASETS}
    if data["dtu"] is None:
        print("no P11-matched results yet"); return
    J, lines = {}, ["# Matched-patch protocol (generated by scripts/make_tab_matched.py from results/P11-matched*)", ""]
    tests = {}
    for name, tag, run in DATASETS:
        d = data[tag]
        if d is None:
            continue
        P = pooled(d)
        J[name] = {"cells": {}, "gray": {}, "tests": {}}
        for m in sorted(P.model.unique()):
            J[name]["cells"][m] = cell(P, m)
            g = cell(d[d.fill_kind == "gray"], m)
            if g:
                J[name]["gray"][m] = g
        # paired tests: heads against their control and against native confidence; label-free against GT placement
        for b, _ in BASES:
            pairs = [(f"{b}_oiamatch", f"{b}_oiamatchpatch"), (f"{b}_oiamatch", b), (f"{b}_oiamatchself", f"{b}_oiamatchselfpatch"),
                     (f"{b}_oiamatchself", b), (f"{b}_oiamatchself", f"{b}_oiamatch"), (f"{b}_oiamatchself", f"{b}_reproj"),
                     (f"{b}_oiavisself", b), (f"{b}_reproj", b)]
            for x, y in pairs:
                if x in P.model.values and y in P.model.values:
                    for c in ("auroc_m", "cur_m", "auroc_m_ev1lo"):
                        dm, p = H.paired_permutation(P, c, x, y)
                        J[name]["tests"][f"{x}:{y}:{c}"] = [round(dm, 4), round(p, 5)]
    # ---- Gate 6: the five native models
    lines += ["## Gate 6: native confidence on the matched split (blur and noise pooled, seeds 0 and 1, evidence 1 / 2 / half)", "",
              "| dataset | model | AUROC (U vs clean S) | AUROC_m (U vs filled-observed) | patch share (a - b) | CUR | CUR_m | AUROC_patch (S vs filled-observed) | (a) leak survives | (b) patch-inflated (> 0.10) |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    gate6 = {}
    for name in J:
        for b, lab in NATIVE:
            c = J[name]["cells"].get(b)
            if not c or c["auroc_m"] is None:
                continue
            share = c["auroc"][0] - c["auroc_m"][0]
            surv = c["cur_m"][1] > 0 and c["auroc_m"][0] < 0.95
            infl = share > 0.10
            gate6[f"{name}:{b}"] = dict(share=round(share, 4), leak_survives=bool(surv), patch_inflated=bool(infl))
            lines.append(f"| {name} | {lab} | {fmt_ci(c['auroc'])} | {fmt_ci(c['auroc_m'])} | {share:+.3f} | {fmt(c['cur'])} | {fmt_ci(c['cur_m'])} | {fmt_ci(c['auroc_patch'])} | {'yes' if surv else 'no'} | {'yes' if infl else 'no'} |")
    J["gate6"] = gate6
    # ---- Gate 7: the matched heads
    lines += ["", "## Gate 7: matched heads (pipeline check first)", "",
              "| dataset | backbone | control AUROC_m (<= 0.60) | head AUROC_m | head - control (p) | head - native (p) | head ev1-low | label-free head AUROC_m | label-free - GT (p) | label-free - control (p) | label-free - native (p) |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    gate7 = {}
    for name in J:
        if name in ("gate6", "gate7", "gate8"):
            continue
        C, T = J[name]["cells"], J[name]["tests"]
        for b, lab in BASES:
            ctrl, head, lf, lfc = C.get(f"{b}_oiamatchpatch"), C.get(f"{b}_oiamatch"), C.get(f"{b}_oiamatchself"), C.get(f"{b}_oiamatchselfpatch")
            if not head:
                continue
            t = lambda k: T.get(k, [float("nan"), float("nan")])
            hc, hn = t(f"{b}_oiamatch:{b}_oiamatchpatch:auroc_m"), t(f"{b}_oiamatch:{b}:auroc_m")
            lg, lc, ln = t(f"{b}_oiamatchself:{b}_oiamatch:auroc_m"), t(f"{b}_oiamatchself:{b}_oiamatchselfpatch:auroc_m"), t(f"{b}_oiamatchself:{b}:auroc_m")
            g = dict(control_ok=bool(ctrl and ctrl["auroc_m"][0] <= 0.60),
                     a_head_beats_control=bool(hc[0] >= 0.10 and hc[1] < 0.05),
                     b_head_beats_native=bool(hn[0] > 0 and hn[1] < 0.05),
                     c_ev1lo=bool(head["auroc_m_ev1lo"] and head["auroc_m_ev1lo"][0] >= 0.75),
                     e_labelfree_within_003=bool(lf and abs(lg[0]) <= 0.03) if lf else None,
                     control_auroc_m=ctrl["auroc_m"][0] if ctrl else None, head_auroc_m=head["auroc_m"][0],
                     labelfree_auroc_m=lf["auroc_m"][0] if lf else None)
            gate7[f"{name}:{b}"] = g
            lines.append(f"| {name} | {lab} | {fmt(ctrl['auroc_m']) if ctrl else '--'} | {fmt_ci(head['auroc_m'])} | {hc[0]:+.3f} ({hc[1]:.4g}) | {hn[0]:+.3f} ({hn[1]:.4g}) | "
                         f"{fmt(head['auroc_m_ev1lo'])} | {fmt_ci(lf['auroc_m']) if lf else '--'} | {lg[0]:+.3f} ({lg[1]:.4g}) | {lc[0]:+.3f} ({lc[1]:.4g}) | {ln[0]:+.3f} ({ln[1]:.4g}) |")
    J["gate7"] = gate7
    # ---- Gate 8: real occlusion against the dense scan (P12-realocc)
    rp = os.path.join(ROOT, "results", "P12-realocc", "P12-realocc.csv")
    if os.path.exists(rp):
        rd = pd.read_csv(rp)
        lines += ["", "## Gate 8: real occlusion against the 49-view scan (P12-realocc)", "",
                  "| views | model | share of predicted points on unobserved surfaces | share off every surface | AUROC observed vs unobserved | head - native (p) |", "|---|---|---|---|---|---|"]
        J["gate8"] = {}
        for n in sorted(rd.n_views.unique()):
            x = rd[rd.n_views == n]
            for m in sorted(x.model.unique()):
                y = x[x.model == m]
                fr = float(y.groupby("scan").frac_unobs.mean().mean()); fo = float(y.groupby("scan").frac_off.mean().mean())
                au = float(y.groupby("scan").auroc_obs_unobs.mean().mean()) if y.auroc_obs_unobs.notna().any() else float("nan")
                base = m.split("_")[0]
                t = H.paired_permutation(x, "auroc_obs_unobs", m, base) if (m != base and base in x.model.values) else (float("nan"), float("nan"))
                J["gate8"][f"{n}:{m}"] = dict(frac_unobs=round(fr, 5), frac_off=round(fo, 4), auroc=round(au, 4), vs_native=[round(t[0], 4), round(t[1], 5)])
                lines.append(f"| {n} | {m} | {100 * fr:.2f}% | {100 * fo:.1f}% | {au:.3f} | {t[0]:+.3f} ({t[1]:.4g}) |")
    # ---- evidence buckets, every detector
    lines += ["", "## AUROC_m per evidence bucket (blur and noise pooled)", "",
              "| dataset | detector | one view, low parallax | one view, high parallax | two views | three or more | AUROC_patch |", "|---|---|---|---|---|---|---|"]
    for name in J:
        if name in ("gate6", "gate7", "gate8"):
            continue
        for m, c in J[name]["cells"].items():
            lines.append(f"| {name} | {m} | {fmt(c['auroc_m_ev1lo'])} | {fmt(c['auroc_m_ev1hi'])} | {fmt(c['auroc_m_ev2'])} | {fmt(c['auroc_m_ev3p'])} | {fmt(c['auroc_patch'])} |")
    lines += ["", "## Paired sign-flip tests (mean difference, p)", ""]
    for name in J:
        if name in ("gate6", "gate7", "gate8"):
            continue
        for k, v in sorted(J[name]["tests"].items()):
            lines.append(f"- {name} {k}: {v[0]:+.4f} (p {v[1]})")
    os.makedirs(a.out, exist_ok=True)
    # ---- LaTeX: native models
    names = [n for n in J if n not in ("gate6", "gate7", "gate8")]
    tex = ["% generated by scripts/make_tab_matched.py from results/P11-matched*", "\\begin{tabular}{l" + "ccccc" * len(names) + "}", "\\toprule",
           "model & " + " & ".join(f"\\multicolumn{{5}}{{c}}{{{n}}}" for n in names) + " \\\\",
           " & " + " & ".join(["\\auroc$\\uparrow$ & \\auroc$_m\\uparrow$ & \\cur$\\downarrow$ & \\cur$_m\\downarrow$ & patch"] * len(names)) + " \\\\", "\\midrule"]
    for b, lab in NATIVE:
        row = [lab]
        for n in names:
            c = J[n]["cells"].get(b)
            row += [fmt(c["auroc"]), fmt(c["auroc_m"]), fmt(c["cur"]), fmt(c["cur_m"]), fmt(c["auroc_patch"])] if c else ["--"] * 5
        tex.append(" & ".join(row) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.out, "tab_matched.tex"), "w", encoding="utf-8", newline="\n").write("\n".join(tex) + "\n")
    # ---- LaTeX: heads
    tex = ["% generated by scripts/make_tab_matched.py from results/P11-matched*", "\\begin{tabular}{l" + "cccccc" * len(names) + "}", "\\toprule",
           "detector & " + " & ".join(f"\\multicolumn{{6}}{{c}}{{{n}}}" for n in names) + " \\\\",
           " & " + " & ".join(["\\auroc$_m\\uparrow$ & \\cur$_m\\downarrow$ & patch & 1 view, low & 1 view, high & 2+ views"] * len(names)) + " \\\\", "\\midrule"]
    for b, lab in BASES:
        if not any(J[n]["cells"].get(f"{b}_oiamatch") for n in names):
            continue
        tex.append(f"\\multicolumn{{{1 + 6 * len(names)}}}{{l}}{{\\emph{{{lab}}}}} \\\\")
        for suf, rlab in HEAD_ROWS:
            m = b + suf
            if not any(J[n]["cells"].get(m) for n in names):
                continue
            row = [rlab]
            for n in names:
                c = J[n]["cells"].get(m)
                ev2 = None
                if c and (c["auroc_m_ev2"] or c["auroc_m_ev3p"]):
                    vals = [v[0] for v in (c["auroc_m_ev2"], c["auroc_m_ev3p"]) if v]
                    ev2 = [float(np.mean(vals))]
                row += [fmt(c["auroc_m"]), fmt(c["cur_m"]), fmt(c["auroc_patch"]), fmt(c["auroc_m_ev1lo"]), fmt(c["auroc_m_ev1hi"]), fmt(ev2)] if c else ["--"] * 6
            tex.append(" & ".join(row) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(a.out, "tab_matched_heads.tex"), "w", encoding="utf-8", newline="\n").write("\n".join(tex) + "\n")
    sp = os.path.join(ROOT, "results", "P11-matched-stats.md")
    open(sp, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    jp = os.path.join(ROOT, "docs", "assets", "matched.json")
    json.dump(J, open(jp, "w", encoding="utf-8"), indent=1)
    print("\n".join(lines[:40]))
    print(f"-> {a.out}/tab_matched.tex, tab_matched_heads.tex, {sp}, {jp}")


if __name__ == "__main__":
    main()
