"""Statistics of the twelfth pass (pre-registered Gate 20 in LOG.md), generated from the CSVs.

  results/P19-nvs/full_{a,b}/P19-nvs.csv   novel-view test (scripts/nvs_eval.py), 15 DTU scans, four backbones

  python scripts/make_stats_p19.py    writes results/P19-stats.md and docs/assets/p19.json"""
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
BASES = ["vggt", "pi3x", "pi3", "da3"]
VARS = ["all", "random", "native", "head", "both"]


def test(x, col, a, b):
    """Mean of (a - b) over scans and its paired sign-flip p; lower is better for LPIPS, higher for PSNR."""
    return H.paired_permutation(x.rename(columns={"model": "backbone", "variant": "model"}), col, a, b)


def main():
    df = pd.concat([pd.read_csv(p) for p in sorted(glob.glob(os.path.join(R, "P19-nvs", "full_*", "P19-nvs.csv")))],
                   ignore_index=True)
    L = ["# Twelfth pass (generated by scripts/make_stats_p19.py; pre-registered in LOG.md)", "",
         "Novel-view test: Gaussian splatting started from the predicted points of the input views, unfiltered (all) or "
         "without 20% of them (random; lowest native confidence; lowest support score; lowest mean rank of both), "
         "identical optimisation, eight held-out rig views. 15 DTU scans, seed 0. Differences are means over scans with "
         "a paired sign-flip p; LPIPS lower is better.", ""]
    J = {"cells": {}}
    nh = 0
    for metric, better in (("lpips", "lower"), ("lpips_common", "lower"), ("psnr", "higher"), ("psnr_common", "higher")):
        L += [f"## {metric} ({better} is better)", "",
              "| backbone | views | scans | " + " | ".join(VARS) + " | head - all (p) | head - native (p) | both - native (p) |",
              "|---|---|---|" + "---|" * (len(VARS) + 3)]
        for b in BASES:
            for n in sorted(df.n_views.unique()):
                x = df[(df.model == b) & (df.n_views == n)]
                if x.empty:
                    continue
                m = x.groupby("variant")[metric].mean()
                ha, hn, bn = test(x, metric, "head", "all"), test(x, metric, "head", "native"), test(x, metric, "both", "native")
                L.append(f"| {b} | {n} | {x.scan.nunique()} | " + " | ".join(f"{m[v]:.3f}" for v in VARS) +
                         f" | {ha[0]:+.3f} ({ha[1]:.4g}) | {hn[0]:+.3f} ({hn[1]:.4g}) | {bn[0]:+.3f} ({bn[1]:.4g}) |")
                c = J["cells"].setdefault(f"{b}:{n}", {})
                c[metric] = dict(means={v: round(float(m[v]), 5) for v in VARS}, head_all=[float(ha[0]), float(ha[1])],
                                 head_native=[float(hn[0]), float(hn[1])], both_native=[float(bn[0]), float(bn[1])])
                if metric == "lpips":
                    holds = bool(ha[0] < 0 and ha[1] < 0.05 and hn[0] < 0 and hn[1] < 0.05)
                    c["holds"] = holds; nh += holds
                    c["train_psnr"] = round(float(x.train_psnr.mean()), 3)
        L.append("")
    cells = J["cells"]
    cnt = lambda k, sign: sum(1 for c in cells.values() if sign * c["lpips"][k][0] < 0 and c["lpips"][k][1] < 0.05)  # noqa: E731
    J.update(gate20=bool(nh >= 4), holds=int(nh), cells_total=len(cells),
             head_better_than_all=cnt("head_all", 1), head_worse_than_all=cnt("head_all", -1),
             head_better_than_native=cnt("head_native", 1), head_worse_than_native=cnt("head_native", -1),
             both_better_than_native=cnt("both_native", 1), both_worse_than_native=cnt("both_native", -1))
    L += [f"**Gate 20 {'passes' if nh >= 4 else 'fails'}:** the head variant has lower held-out LPIPS than both the "
          f"unfiltered and the native-confidence variant (each p < 0.05) in {nh} of {len(cells)} cells.", "",
          f"Held-out LPIPS, cells with a significant difference (p < 0.05): head better than unfiltered in "
          f"{J['head_better_than_all']}, worse in {J['head_worse_than_all']}; head better than native confidence in "
          f"{J['head_better_than_native']}, worse in {J['head_worse_than_native']}; both better than native confidence in "
          f"{J['both_better_than_native']}, worse in {J['both_worse_than_native']} (of {len(cells)})."]
    open(os.path.join(R, "P19-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p19.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
