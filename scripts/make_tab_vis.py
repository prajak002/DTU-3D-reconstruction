"""LaTeX fragments of the true-visibility results, generated from the run CSVs so that no number is typed by hand.

  python scripts/make_tab_vis.py [--out paper/tex]      writes tab_vis.tex (main table), tab_vis_supp.tex (every detector,
                                                        with intervals), tab_bands.tex (operating points, from the dump analysis)

Main table: one row per detector, AUROC / CUR pooled over scenes and view counts (3, 5, 10 on DTU and ETH3D; 3 and 5
on CO3Dv2 and phototourism, where ten views around an object leave no single-view pixel), DTU | CO3Dv2 | ETH3D |
Phototourism columns, blocks per backbone. Means over scene means; the 95% cluster-bootstrap intervals and the paired
tests are in the supplement table and in results/P3-stats.md."""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = [("DTU", "P4-vis", None), ("CO3Dv2", "P4-vis-co3d", "P6-adapt-co3d"), ("ETH3D", "P4-vis-eth3d", "P6-adapt-eth3d"),
        ("Photot.", "P7-vis-imc", "P7-adapt-imc")]
BASES = [("vggt", "VGGT-1B"), ("pi3x", "Pi3X"), ("pi3", "Pi3"), ("da3", "Depth Anything 3")]
# (suffix, label, in main table)
DETECTORS = [("", "native confidence", True), ("reproj", "reprojection consistency", True),
             ("border", "distance to image border", True), ("dedge", "depth edges", True),
             ("oia", "fill-trained head", False), ("oiapatch", "fill-trained per-image control", False),
             ("oiavispatch", "per-image control (GT labels)", True), ("oiavislin", "linear probe (GT labels)", True),
             ("oiavis", "support head, GT visibility labels", True),
             ("oiavisselfpatch", "per-image control (self labels)", True), ("oiavisselflin", "linear probe (self labels)", False),
             ("oiavisself", "\\textbf{support head, label-free}", True),
             ("oiavisself_x", "label-free head, adapted on the target domain", True)]


def load(run, adapt):
    p = os.path.join(ROOT, "results", run, f"{run}.csv")
    if not os.path.exists(p):
        return None
    d = pd.read_csv(p)
    if adapt:
        pa = os.path.join(ROOT, "results", adapt, f"{adapt}.csv")
        if os.path.exists(pa):
            a = pd.read_csv(pa)
            a["model"] = a.model.str.replace(r"_x(co3d|eth3d|imc)[AB]$", "_x", regex=True)
            d = pd.concat([d, a], ignore_index=True)
    if "skipped" in d:
        d = d[~d.skipped.astype(bool)]
    return d


def cell(d, model, ci=False):
    x = d[d.model == model] if d is not None else pd.DataFrame()
    if x.empty:
        return "-- & --"
    if ci:
        a = H.cluster_bootstrap_ci(x, "auroc", n_boot=5000); c = H.cluster_bootstrap_ci(x, "cur", n_boot=5000)
        return f"\\ci{{{a[0]:.3f}}}{{{a[1]:.3f}}}{{{a[2]:.3f}}} & \\ci{{{c[0]:.3f}}}{{{c[1]:.3f}}}{{{c[2]:.3f}}}"
    m = x.groupby("scan")[["auroc", "cur"]].mean().mean()
    return f"{m.auroc:.3f} & {m.cur:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    data = {name: load(run, adapt) for name, run, adapt in RUNS}
    present = [n for n in data if data[n] is not None]
    for fname, with_ci, main_only in (("tab_vis.tex", False, True), ("tab_vis_supp.tex", True, False)):
        lines = []
        for bi, (base, blabel) in enumerate(BASES):
            if main_only and base == "da3":            # DA3 is quoted in the text; the supplement table has its block
                continue
            rows = []
            for suf, label, in_main in DETECTORS:
                if main_only and not in_main:
                    continue
                if main_only and suf == "oiavislin":          # the probe is quoted in the text; supplement table has it
                    continue
                if main_only and suf in ("border", "dedge") and bi > 0:   # the heuristics do not depend on the backbone
                    continue
                if main_only and suf in ("border", "dedge"):
                    label += " (any backbone)"
                model = base if suf == "" else f"{base}_{suf}"
                cells = [cell(data[n], model, with_ci) for n in present]
                if all(c == "-- & --" for c in cells):
                    continue
                rows.append(f"{label} & " + " & ".join(cells) + r" \\")
            if rows:
                lines.append(r"\multicolumn{%d}{l}{\emph{%s}} \\" % (1 + 2 * len(present), blabel))
                lines += rows
        head = "detector & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{n}}}" for n in present) + r" \\"
        sub = " & " + " & ".join(r"\auroc & \cur" for _ in present) + r" \\"
        out = os.path.join(a.out, fname)
        open(out, "w", encoding="utf-8", newline="\n").write(
            "% generated by scripts/make_tab_vis.py from results/P4-vis*, P7-vis-imc, P6-adapt-*, P7-adapt-imc\n"
            + "\\begin{tabular}{l*{%d}{cc}}\n\\toprule\n" % len(present)
            + head + "\n" + sub + "\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
        print("->", out, len(lines), "rows; datasets", present)
    # cross-model disagreement on the filled patches and on real single-view geometry
    xm = {}
    for key, run, flt in (("fill_dtu", "P8-xmodel", None), ("fill_co3d", "P8-xmodel-co3d", None), ("vis_dtu", "P8-xmodel-vis", None)):
        p = os.path.join(ROOT, "results", run, f"{run}.csv")
        if os.path.exists(p):
            d = pd.read_csv(p)
            xm[key] = d[~d.skipped.astype(bool)] if "skipped" in d else d
    if xm:
        pairs = sorted({m for d in xm.values() for m in d.model.unique()})
        rows = []
        for m in pairs:
            cells = " & ".join(cell(xm[k], m, True) if k in xm else "-- & --" for k in ("fill_dtu", "fill_co3d", "vis_dtu"))
            rows.append(m.replace("_x", " against ").replace("vggt", "VGGT-1B").replace("pi3x", "Pi3X").replace("pi3", "Pi3").replace("da3", "DA3").replace("mapanything", "MapAnything") + " & " + cells + r" \\")
        out = os.path.join(a.out, "tab_xmodel.tex")
        open(out, "w", encoding="utf-8", newline="\n").write(
            "% generated by scripts/make_tab_vis.py from results/P8-xmodel*\n\\begin{tabular}{l*{3}{cc}}\n\\toprule\n"
            r"pair & \multicolumn{2}{c}{filled patch, DTU} & \multicolumn{2}{c}{filled patch, CO3Dv2} & \multicolumn{2}{c}{single-view, DTU} \\" "\n"
            r" & \auroc & \cur & \auroc & \cur & \auroc & \cur \\" "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
        print("->", out, len(rows), "pairs")
    # fused point clouds at matched coverage
    fz = {}
    for key in ("dtu", "eth3d"):
        p = os.path.join(ROOT, "results", "P8-fuse", f"P8-fuse-{key}.csv")
        if os.path.exists(p):
            fz[key] = pd.read_csv(p)
    if fz:
        dets = [("vggt", "native confidence"), ("vggt_reproj", "reprojection consistency"), ("vggt_oiavispatch", "per-image control"),
                ("vggt_oiavisself", "label-free head"), ("vggt_random", "random dropping"), ("vggt_oracle", "oracle: single-view first"),
                ("pi3x", "native confidence (Pi3X)"), ("pi3x_reproj", "reprojection (Pi3X)"), ("pi3x_oiavisself", "label-free head (Pi3X)"), ("pi3x_oracle", "oracle (Pi3X)")]
        rows = []
        for m, lab in dets:
            cells = []
            for key in ("dtu", "eth3d"):
                d = fz.get(key)
                for cov in (0.6, 0.8, 1.0):
                    x = d[(d.model == m) & (d.coverage == cov)] if d is not None else None
                    cells.append(f"{x.accuracy.mean():.3f} / {x.completeness.mean():.3f}" if x is not None and len(x) else "--")
            rows.append(lab + " & " + " & ".join(cells) + r" \\")
        out = os.path.join(a.out, "tab_fuse.tex")
        open(out, "w", encoding="utf-8", newline="\n").write(
            "% generated by scripts/make_tab_vis.py from results/P8-fuse\n\\begin{tabular}{l*{6}{c}}\n\\toprule\n"
            r"detector & \multicolumn{3}{c}{DTU, accuracy / completeness} & \multicolumn{3}{c}{ETH3D, accuracy / completeness} \\" "\n"
            r"coverage & 0.6 & 0.8 & 1.0 & 0.6 & 0.8 & 1.0 \\" "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
        print("->", out, len(rows), "rows")
    # operating points from the dump analysis, if present
    bands = []
    for name, run, _ in RUNS:
        ds = {"DTU": "dtu", "CO3Dv2": "co3d", "ETH3D": "eth3d", "Photot.": "imc"}[name]
        p = os.path.join(ROOT, "results", "P6-dump", f"P6-dump-{ds}_curves.csv")
        if not os.path.exists(p):
            continue
        c = pd.read_csv(p)
        for base, blabel in BASES:
            for suf, label in (("", "native confidence"), ("reproj", "reprojection"), ("oiavis", "head, GT labels"), ("oiavisself", "head, label-free")):
                model = base if suf == "" else f"{base}_{suf}"
                r = c[c.model == model]
                if r.empty:
                    continue
                r = r.iloc[0]
                fz = f"{r['cur_frozen']:.2f} / {r['keep_frozen']:.2f}" if "cur_frozen" in r and np.isfinite(r.get("cur_frozen", np.nan)) else "--"
                lo = f"{r['cur_loso']:.2f} / {r['keep_loso']:.2f}" if "cur_loso" in r and np.isfinite(r.get("cur_loso", np.nan)) else "--"
                bd = (f"{r['frac_observed']:.2f} / {r['frac_abstain']:.2f} / {r['frac_imagined']:.2f} & {r['risk_observed']:.3f} & {r['absrel_observed']:.3f}"
                      if "frac_observed" in r and np.isfinite(r.get("frac_observed", np.nan)) else "-- & -- & --")
                bands.append(f"{name} & {blabel} & {label} & {r['aurc']:.3f} & {r['absrel_all']:.3f} & {r['absrel50']:.3f} & {lo} & {fz} & {bd} \\\\")
    if bands:
        out = os.path.join(a.out, "tab_bands.tex")
        head = (r"dataset & backbone & detector & AURC & AbsRel all & AbsRel top half & CUR / keep (a) & CUR / keep (b) & "
                r"obs. / abst. / imag. & single-view in obs. & AbsRel in obs. \\")
        open(out, "w", encoding="utf-8", newline="\n").write(
            "% generated by scripts/make_tab_vis.py from results/P6-dump/*_curves.csv\n"
            "\\begin{tabular}{lll*{8}{c}}\n\\toprule\n" + head + "\n\\midrule\n" + "\n".join(bands) + "\n\\bottomrule\n\\end{tabular}\n")
        print("->", out, len(bands), "rows")


if __name__ == "__main__":
    main()
