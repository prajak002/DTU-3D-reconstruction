"""Statistics of the thirteenth pass (pre-registered Gate 21 in LOG.md), generated from the CSVs.

  results/P20-baselines/{vggt,pi3x,pi3,da3}/P12-realocc-tum.csv    TUM RGB-D, 3, 5 and 10 views
  results/P20-baselines/{vggt,pi3x,pi3,da3}_dtu/P12-realocc.csv    DTU benchmark scans, 3 views

Four detectors per backbone in one job (native confidence, the label-free head, the aligned perturbation variance
`_pvf8`, reprojection `_reproj`), hole-robust labels.

  python scripts/make_stats_p20.py    writes results/P20-stats.md and docs/assets/p20.json"""
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402
from make_stats_p17 import BASES, R, ROOT  # noqa: E402

SETS = [("TUM RGB-D", "{b}", "P12-realocc-tum.csv"), ("DTU benchmark", "{b}_dtu", "P12-realocc.csv")]


def load(sub, name):
    parts = [pd.read_csv(p) for b in BASES
             for p in glob.glob(os.path.join(R, "P20-baselines", sub.format(b=b), name))]
    return pd.concat(parts, ignore_index=True) if parts else None


def mean_auroc(x, model):
    return float(x[x.model == model].groupby("scan").auroc_obs_unobs.mean().mean())


def main():
    L = ["# Thirteenth pass (generated by scripts/make_stats_p20.py; pre-registered in LOG.md)", "",
         "Real occlusion with hole-robust labels; four detectors per backbone scored in one job on the same points. "
         "A cell counts for the gate when the unobserved share averages at least 0.5%; in it the claim holds if the "
         "DTU-trained label-free head beats the aligned perturbation variance (K = 8) at p < 0.05 (paired sign-flip "
         "over scenes). Reprojection with the model's own cameras is reported with the same test and no rule.", ""]
    J = {"cells": {}}
    nq = nh = nr = 0
    for name, sub, fn in SETS:
        df = load(sub, fn)
        if df is None:
            L += [f"## {name}: no rows", ""]
            continue
        L += [f"## {name}", "",
              "| views | backbone | scenes | unobserved share | native | perturbation | reprojection | head | "
              "head - perturbation (p) | head - reprojection (p) | head - native (p) | holds |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for n in sorted(df.n_views.unique()):
            x = df[df.n_views == n]
            for b in BASES:
                need = [b, f"{b}_oiavisself", f"{b}_pvf8", f"{b}_reproj"]
                if any(m not in x.model.values for m in need):
                    continue
                share = float(x[x.model == b].groupby("scan").frac_unobs.mean().mean())
                tp = H.paired_permutation(x, "auroc_obs_unobs", need[1], need[2])
                tr = H.paired_permutation(x, "auroc_obs_unobs", need[1], need[3])
                tn = H.paired_permutation(x, "auroc_obs_unobs", need[1], need[0])
                q = share >= 0.005
                holds = bool(q and tp[0] > 0 and tp[1] < 0.05)
                nq += q; nh += holds; nr += bool(q and tr[0] > 0 and tr[1] < 0.05)
                c = dict(share=share, native=mean_auroc(x, need[0]), head=mean_auroc(x, need[1]),
                         perturbation=mean_auroc(x, need[2]), reprojection=mean_auroc(x, need[3]),
                         d_pert=float(tp[0]), p_pert=float(tp[1]), d_reproj=float(tr[0]), p_reproj=float(tr[1]),
                         d_native=float(tn[0]), p_native=float(tn[1]), qualifies=bool(q), holds=holds,
                         n=int(x[x.model == b].scan.nunique()))
                J["cells"][f"{name}:{n}:{b}"] = {k: (round(v, 5) if isinstance(v, float) else v) for k, v in c.items()}
                L.append(f"| {n} | {b} | {c['n']} | {100 * share:.2f}% | {c['native']:.3f} | {c['perturbation']:.3f} | "
                         f"{c['reprojection']:.3f} | {c['head']:.3f} | {tp[0]:+.3f} ({tp[1]:.4g}) | "
                         f"{tr[0]:+.3f} ({tr[1]:.4g}) | {tn[0]:+.3f} ({tn[1]:.4g}) | "
                         f"{'yes' if holds else ('no' if q else 'n/a')} |")
        L.append("")
    ok = nq > 0 and 4 * nh >= 3 * nq
    J.update(qualifying=int(nq), holds=int(nh), beats_reprojection=int(nr), gate21=bool(ok))
    L += [f"**Gate 21 {'passes' if ok else 'fails'}:** the head beats the aligned perturbation variance in {nh} of "
          f"{nq} qualifying cells (needed: three quarters). Reported, no rule: it beats reprojection at p < 0.05 in "
          f"{nr} of {nq}."]
    open(os.path.join(R, "P20-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    os.makedirs(os.path.join(ROOT, "docs", "assets"), exist_ok=True)
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p20.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
