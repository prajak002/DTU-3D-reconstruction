"""Statistics of the tenth pass (pre-registered Gate 18 in LOG.md), generated from the CSVs.

  results/P17-zagree/{eth,dtu,dext,co3d}_{a,b}/P12-realocc*.csv   real occlusion with hole-robust labels
                                                                  (realocc_eval.py --label-mode zagree)

  python scripts/make_stats_p17.py    writes results/P17-stats.md and docs/assets/p17.json"""
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
BASES = ["vggt", "pi3x", "pi3", "da3"]
SETS = [("ETH3D", "eth", "primary"), ("DTU benchmark", "dtu", "secondary"), ("DTU test", "dext", "secondary"),
        ("CO3Dv2", "co3d", "secondary")]


def load(key):
    parts = [pd.read_csv(p) for p in sorted(glob.glob(os.path.join(R, "P17-zagree", f"{key}_*", "P12-realocc*.csv")))
             if not p.endswith("_summary.csv")]
    return pd.concat(parts, ignore_index=True) if parts else None


def cell(x, head, base):
    y = x[x.model == base]
    fr = float(y.groupby("scan").frac_unobs.mean().mean())
    am = float(y.groupby("scan").frac_amb.mean().mean())
    pts = bool((x["align"] == "points").all())
    al = float(y.groupby("scan").onsurf_valid.mean().mean())
    an = float(y.groupby("scan").auroc_obs_unobs.mean().mean())
    ah = float(x[x.model == head].groupby("scan").auroc_obs_unobs.mean().mean())
    t = H.paired_permutation(x, "auroc_obs_unobs", head, base)
    q = fr >= 0.005 and (al >= 0.5 if pts else True)
    holds = bool(q and t[0] > 0 and t[1] < 0.05)
    return dict(share=fr, amb=am, onsurf=al, points=pts, native=an, head=ah, diff=float(t[0]), p=float(t[1]),
                qualifies=bool(q), holds=holds, n=int(y.scan.nunique()))


def rounded(c):
    return {k: (round(v, 5) if isinstance(v, float) else v) for k, v in c.items()}


def main():
    L = ["# Tenth pass (generated by scripts/make_stats_p17.py; pre-registered in LOG.md)", "",
         "Hole-robust labels: a ground-truth point the depth test calls unobserved but a z-buffer of the whole scan calls "
         "visible in an input view is ambiguous and left out of both classes. A cell qualifies if the unobserved share "
         "averages at least 0.5% (and, where the alignment is fitted on pixels, at least 0.5 of them lie on the scanned "
         "surface); the claim holds if the label-free head beats native confidence at p < 0.05 (paired sign-flip over "
         "scenes).", ""]
    J = {"cells": {}, "sets": {}}
    for name, key, role in SETS:
        df = load(key)
        if df is None:
            L += [f"## {name}: no rows", ""]
            continue
        L += [f"## {name} ({role})", "",
              "| views | backbone | scenes | ambiguous share | unobserved share | aligned on surface | qualifies | "
              "native AUROC | head AUROC | head - native (p) | claim holds |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        nq = nh = 0
        for n in sorted(df.n_views.unique()):
            x = df[df.n_views == n]
            for b in BASES:
                if b not in x.model.values or f"{b}_oiavisself" not in x.model.values:
                    continue
                c = cell(x, f"{b}_oiavisself", b)
                nq += c["qualifies"]
                nh += c["holds"]
                J["cells"][f"{name}:{n}:{b}"] = rounded(c)
                L.append(f"| {n} | {b} | {c['n']} | {100 * c['amb']:.2f}% | {100 * c['share']:.2f}% | {c['onsurf']:.3f} | "
                         f"{'yes' if c['qualifies'] else 'no'} | {c['native']:.3f} | {c['head']:.3f} | "
                         f"{c['diff']:+.3f} ({c['p']:.4g}) | {'yes' if c['holds'] else ('no' if c['qualifies'] else 'n/a')} |")
        J["sets"][name] = dict(qualifying=int(nq), holds=int(nh))
        L += ["", f"{name}: the claim holds in {nh} of {nq} qualifying cells.", ""]
        if key == "eth":
            rows = []
            for n in sorted(df.n_views.unique()):
                x = df[df.n_views == n]
                for b in ("vggt", "pi3x"):
                    h = f"{b}_oiavisself_xeth3d"
                    if h in x.model.values and b in x.model.values:
                        c = cell(x, h, b)
                        J["cells"][f"{name}-adapted:{n}:{b}"] = rounded(c)
                        rows.append(f"| {n} | {b} | {c['n']} | {c['native']:.3f} | {c['head']:.3f} | "
                                    f"{c['diff']:+.3f} ({c['p']:.4g}) |")
            if rows:
                L += ["Heads adapted on ETH3D images without labels (P6-adapt-eth3d; reported, not counted in the gate):", "",
                      "| views | backbone | scenes | native AUROC | adapted head AUROC | head - native (p) |",
                      "|---|---|---|---|---|---|"] + rows + [""]
    e = J["sets"].get("ETH3D")
    if e:
        ok = e["qualifying"] >= 6 and 2 * e["holds"] >= e["qualifying"]
        J["gate18"] = bool(ok)
        L.append(f"**Gate 18 {'passes' if ok else 'fails'}:** on ETH3D the claim holds in {e['holds']} of "
                 f"{e['qualifying']} qualifying cells.")
    open(os.path.join(R, "P17-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p17.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
