"""Compact true-visibility table for the paper body (tab_vis_compact.tex), generated from docs/assets/numbers.json:
one row per detector, AUROC and CUR per dataset as the mean over the four backbones (VGGT-1B, Pi3X, Pi3, Depth Anything 3),
our rows tinted, the best value per column in bold. The per-backbone table with intervals is in the supplement.

  python scripts/make_tab_summary.py [--out paper/tex]"""
import argparse
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASES = ("vggt", "pi3x", "pi3", "da3")
DS = [("dtu", "DTU"), ("co3d", "CO3Dv2"), ("eth3d", "ETH3D"), ("imc", "Photot.")]
ROWS = [("", "native confidence", False), ("_border", "image-border cue", False), ("_oiavisselfpatch", "per-image control", False),
        ("_reproj", "reprojection, own cameras", False), ("_oiavis", "support head, GT labels", True),
        ("_oiavisself", "\\textbf{support head, label-free}", True)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    V = json.load(open(os.path.join(ROOT, "docs", "assets", "numbers.json"), encoding="utf-8"))["vis"]
    cell = {}
    for suf, _, _ in ROWS:
        for k, _ in DS:
            v = [V[k][f"{b}{suf}"] for b in BASES if f"{b}{suf}" in V[k]]
            cell[(suf, k)] = (float(np.mean([x["auroc"][0] for x in v])) if v else None, float(np.mean([x["cur"][0] for x in v])) if v else None, len(v))
    best = {}
    for k, _ in DS:
        aus = [cell[(s, k)][0] for s, _, _ in ROWS if cell[(s, k)][0] is not None]
        cus = [cell[(s, k)][1] for s, _, _ in ROWS if cell[(s, k)][1] is not None]
        best[k] = (max(aus), min(cus))
    lines = []
    for suf, lab, ours in ROWS:
        row = [lab]
        for k, _ in DS:
            au, cu, n = cell[(suf, k)]
            f = lambda x, b: "--" if x is None else (f"\\textbf{{{x:.2f}}}" if f"{x:.2f}" == f"{b:.2f}" else f"{x:.2f}")
            row += [f(au, best[k][0]), f(cu, best[k][1])]
        lines.append(("\\rowcolor{oursbg} " if ours else "") + " & ".join(row) + " \\\\")
    tex = ("% generated by scripts/make_tab_summary.py from docs/assets/numbers.json (mean over VGGT-1B, Pi3X, Pi3, Depth Anything 3)\n"
           "\\begin{tabular}{l*{4}{cc}}\n\\toprule\n"
           + " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{n}}}" for _, n in DS) + " \\\\\n"
           + "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(DS))) + "\n"
           + "detector & " + " & ".join(["\\auroc$\\uparrow$ & \\cur$\\downarrow$"] * len(DS)) + " \\\\\n\\midrule\n"
           + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
    out = os.path.join(a.out, "tab_vis_compact.tex")
    open(out, "w", encoding="utf-8", newline="\n").write(tex)
    print("->", out)
    print(tex)


if __name__ == "__main__":
    main()
