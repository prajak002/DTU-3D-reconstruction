"""Compact leak table for the main paper (tab_leak.tex), generated from the full-configuration CSVs so that no number
is typed by hand: five models, DTU and CO3Dv2 side by side, pooled over the two natural-statistics fills (blur and
noise) and both radii: AUROC and CUR with 95% cluster-bootstrap intervals over scenes, CUR-err, and the confidence
ratio (median confidence inside the hidden region over its clean value). The per-fill tables with every column stay
in the supplement.

  python scripts/make_tab_leak.py [--out paper/tex]"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("vggt", "VGGT-1B"), ("pi3", "Pi3"), ("pi3x", "Pi3X"), ("mapanything", "MapAnything"), ("da3", "Depth Anything 3")]


def cells(d, m):
    x = d[(d.model == m) & d.fill.isin(["blur", "noise"])]
    if x.empty:
        return "-- & -- & -- & --"
    a = H.cluster_bootstrap_ci(x, "auroc", n_boot=10000)
    c = H.cluster_bootstrap_ci(x, "cur", n_boot=10000)
    g = x.groupby("scan")[["cur_err", "conf_ratio_U"]].mean().mean()
    return f"\\ci{{{a[0]:.3f}}}{{{a[1]:.3f}}}{{{a[2]:.3f}}} & \\ci{{{c[0]:.3f}}}{{{c[1]:.3f}}}{{{c[2]:.3f}}} & {g.cur_err:.3f} & {g.conf_ratio_U:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    dtu = pd.read_csv(os.path.join(ROOT, "results", "table1_all_models.csv"))
    co3d = pd.read_csv(os.path.join(ROOT, "results", "table3_all_models.csv"))
    rows = [f"{label} & {cells(dtu, m)} & {cells(co3d, m)} \\\\" for m, label in MODELS]
    out = os.path.join(a.out, "tab_leak.tex")
    open(out, "w", encoding="utf-8", newline="\n").write(
        "% generated by scripts/make_tab_leak.py from results/table1_all_models.csv and table3_all_models.csv\n"
        "\\begin{tabular}{l*{2}{cccc}}\n\\toprule\n"
        r"model & \multicolumn{4}{c}{DTU, 18 scans} & \multicolumn{4}{c}{CO3Dv2, 18 scenes} \\" "\n"
        r" & \auroc & \cur & \curerr & conf ratio & \auroc & \cur & \curerr & conf ratio \\" "\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    print("->", out, len(rows), "rows")


if __name__ == "__main__":
    main()
