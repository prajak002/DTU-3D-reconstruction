"""Compact leak table for the main paper (tab_leak.tex), generated from the full-configuration CSVs so that no number
is typed by hand: five models, DTU and CO3Dv2 side by side, pooled over the two natural-statistics fills (blur and
noise) and both radii: AUROC and CUR with 95% cluster-bootstrap intervals over scenes, CUR-err, and the confidence
ratio (median confidence inside the hidden region over its clean value). The per-fill tables with every column stay
in the supplement.

  python scripts/make_tab_leak.py [--out paper/tex]"""
import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("vggt", "VGGT-1B"), ("pi3", "Pi3"), ("pi3x", "Pi3X"), ("mapanything", "MapAnything"), ("da3", "Depth Anything 3")]


def _matched():
    """The matched split (run P11-matched, docs/assets/matched.json): AUROC_m and CUR_m per dataset and model."""
    import json
    p = os.path.join(ROOT, "docs", "assets", "matched.json")
    if not os.path.exists(p):
        return None
    J = json.load(open(p, encoding="utf-8"))
    return {"dtu": J.get("DTU", {}).get("cells", {}), "co3d": J.get("CO3Dv2", {}).get("cells", {})}


MATCHED = _matched()


def cells(d, m, key=None):
    x = d[(d.model == m) & d.fill.isin(["blur", "noise"])]
    mc = (MATCHED or {}).get(key, {}).get(m) if MATCHED and key else None
    tail = (f" & {mc['auroc_m'][0]:.3f} & {mc['cur_m'][0]:.3f}" if mc and mc.get("auroc_m") and mc.get("cur_m") else (" & -- & --" if MATCHED else ""))
    if x.empty:
        return "-- & -- & -- & --" + tail
    a = H.cluster_bootstrap_ci(x, "auroc", n_boot=10000)
    c = H.cluster_bootstrap_ci(x, "cur", n_boot=10000)
    g = x.groupby("scan")[["cur_err", "conf_ratio_U"]].mean().mean()
    return f"\\ci{{{a[0]:.3f}}}{{{a[1]:.3f}}}{{{a[2]:.3f}}} & \\ci{{{c[0]:.3f}}}{{{c[1]:.3f}}}{{{c[2]:.3f}}} & {g.cur_err:.3f} & {g.conf_ratio_U:.2f}" + tail


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    dtu = pd.read_csv(os.path.join(ROOT, "results", "table1_all_models.csv"))
    co3d = pd.read_csv(os.path.join(ROOT, "results", "table3_all_models.csv"))
    rows = [f"{label} & {cells(dtu, m, 'dtu')} & {cells(co3d, m, 'co3d')} \\\\" for m, label in MODELS]
    k = 6 if MATCHED else 4
    extra = r" & \auroc$_m\uparrow$ & \cur$_m\downarrow$" if MATCHED else ""
    # full version with intervals (supplement)
    out = os.path.join(a.out, "tab_leak_full.tex")
    open(out, "w", encoding="utf-8", newline="\n").write(
        "% generated by scripts/make_tab_leak.py from results/table1_all_models.csv and table3_all_models.csv\n"
        "\\begin{tabular}{l*{2}{c" + "c" * (k - 1) + "}}\n\\toprule\n"
        + f"model & \\multicolumn{{{k}}}{{c}}{{DTU, 18 scans}} & \\multicolumn{{{k}}}{{c}}{{CO3Dv2, 18 scenes}} \\\\" "\n"
        + r" & \auroc$\uparrow$ & \cur$\downarrow$ & \curerr$\downarrow$ & conf ratio" + extra + r" & \auroc$\uparrow$ & \cur$\downarrow$ & \curerr$\downarrow$ & conf ratio" + extra + r" \\" "\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    print("->", out, len(rows), "rows")
    # compact version for the body: means only, the matched columns shaded
    def compact(d, m, key):
        x = d[(d.model == m) & d.fill.isin(["blur", "noise"])]
        g = x.groupby("scan")[["auroc", "cur"]].mean().mean()
        mc = (MATCHED or {}).get(key, {}).get(m)
        mm = f" & {mc['auroc_m'][0]:.2f} & {mc['cur_m'][0]:.2f}" if mc else " & -- & --"
        return f"{g.auroc:.2f} & {g.cur:.2f}" + mm
    rows_c = [f"{label} & {compact(dtu, m, 'dtu')} & {compact(co3d, m, 'co3d')} \\\\" for m, label in MODELS]
    out = os.path.join(a.out, "tab_leak.tex")
    open(out, "w", encoding="utf-8", newline="\n").write(
        "% generated by scripts/make_tab_leak.py (compact body version; intervals in tab_leak_full.tex)\n"
        "\\begin{tabular}{l cc >{\\columncolor{matchbg}}c >{\\columncolor{matchbg}}c cc >{\\columncolor{matchbg}}c >{\\columncolor{matchbg}}c}\n\\toprule\n"
        r" & \multicolumn{4}{c}{DTU (lab rig)} & \multicolumn{4}{c}{CO3Dv2 (phone)} \\" "\n"
        r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}" "\n"
        r" & \multicolumn{2}{c}{vs clean} & \multicolumn{2}{c}{\cellcolor{matchbg}vs observed patch} & \multicolumn{2}{c}{vs clean} & \multicolumn{2}{c}{\cellcolor{matchbg}vs observed patch} \\" "\n"
        r"model & \auroc$\uparrow$ & \cur$\downarrow$ & \auroc$\uparrow$ & \cur$\downarrow$ & \auroc$\uparrow$ & \cur$\downarrow$ & \auroc$\uparrow$ & \cur$\downarrow$ \\" "\n\\midrule\n"
        + "\n".join(rows_c) + "\n\\bottomrule\n\\end{tabular}\n")
    print("->", out, len(rows_c), "rows (compact)")


if __name__ == "__main__":
    main()
