"""The Overleaf project archive: paper/observe_imagine_abstain_overleaf.zip. Flat layout (Overleaf's main document
is main.tex at the root), figures as PDF under figures/, the generated table fragments included, graphicspath
rewritten for the flat layout, and a README with the compile settings. Run from anywhere:

  python scripts/make_overleaf.py [--out paper/observe_imagine_abstain_overleaf.zip]
"""
import argparse
import glob
import os
import time
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEX = os.path.join(ROOT, "paper", "tex")
FIGS = os.path.join(ROOT, "paper", "figures")

README = """# Observe, Imagine, Abstain (CVPR 2027 submission) - Overleaf project

Upload this zip as a new Overleaf project (New Project > Upload Project).

Settings (Menu, top left):
- Compiler: pdfLaTeX
- TeX Live version: 2024 or 2025
- Main document: main.tex (the paper: eight pages of body, then the LLM Usage Statement and the references)
- To build the supplementary, switch Main document to supp.tex and recompile (six pages).

Files:
- main.tex            the paper (sections, tables, captions)
- preamble.tex        document class, packages, macros (\\ci for a value with its interval)
- supp.tex            supplementary wrapper; supp_body.tex holds its text, tables and figures
- tab_vis.tex, tab_vis_supp.tex, tab_bands.tex
                      table bodies generated from the result CSVs by scripts/make_tab_vis.py in the code
                      repository (no number typed by hand); main.tex and supp_body.tex \\input them
- refs.bib            bibliography (ieeenat_fullname.bst, the CVPR author-kit style)
- cvpr.sty            CVPR 2027 author kit, review mode (anonymous, line numbers)
- figures/            the figures as PDF; regenerated by scripts/make_figures.py in the code repository

Notes:
- Every number in the paper comes from a logged run in results/ of the code repository; there are no
  pending cells. The pre-registered pass conditions, with dates and commit hashes, are in the supplement.
- The body must end on page 8; the LLM Usage Statement and the references do not count toward the limit.
  The build of %s ends the body on page 8 with TeX Live 2023 (pdfLaTeX); if a different TeX Live
  shifts a line, the two narrowest places are the Table 3 caption and the limitations paragraph.
- cvpr.sty with the [review] option prints line numbers and hides the authors; for the camera-ready, change
  \\usepackage[review]{cvpr} to \\usepackage[pagenumbers]{cvpr} in preamble.tex and fill in the author block.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "observe_imagine_abstain_overleaf.zip"))
    a = ap.parse_args()
    tex_files = ["main.tex", "preamble.tex", "supp.tex", "supp_body.tex", "refs.bib", "cvpr.sty", "ieeenat_fullname.bst"]
    tex_files += [os.path.basename(p) for p in sorted(glob.glob(os.path.join(TEX, "tab_*.tex")))]
    with zipfile.ZipFile(a.out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in tex_files:
            p = os.path.join(TEX, f)
            data = open(p, "rb").read()
            if f == "preamble.tex":
                data = data.replace(b"\\graphicspath{{../figures/}}", b"\\graphicspath{{figures/}}")
            z.writestr(f, data)
        for p in sorted(glob.glob(os.path.join(FIGS, "*.pdf"))):
            z.write(p, "figures/" + os.path.basename(p))
        z.writestr("README_OVERLEAF.md", README % time.strftime("%Y-%m-%d"))
        names = z.namelist()
    print("->", a.out, len(names), "files:", ", ".join(n for n in names if not n.startswith("figures/")), "+", sum(n.startswith("figures/") for n in names), "figures")


if __name__ == "__main__":
    main()
