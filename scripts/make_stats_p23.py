"""Statistics of the sixteenth pass (declared in LOG.md before any run), generated from the CSVs.

  results/P23-dynamic/{vggt,pi3x,pi3,da3}/P23-dynamic.csv   moving scenes, full video (scripts/dynamic_eval.py)

  python scripts/make_stats_p23.py    writes results/P23-stats.md and docs/assets/p23.json"""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
BASES = ("vggt", "pi3x", "pi3", "da3")
MIN_SEQ = 6            # fewer sequences with both classes: the sign-flip test cannot reach p < 0.05
FLOOR_RATIO = 0.25     # share of M on static sequences over the share on dynamic ones, above which M is not read
COLS = ("auroc_SU", "auroc_SM", "auroc_UM", "auroc_S_Umixed", "absrel_S", "absrel_U", "absrel_M")


def seqmean(x, model, col):
    return x[x.model == model].groupby("scan")[col].mean().dropna()


def compare(x, head, base, col):
    a, b = seqmean(x, head, col), seqmean(x, base, col)
    n = len(a.index.intersection(b.index))
    d, p = H.paired_permutation(x, col, head, base) if n >= 2 else (float("nan"), float("nan"))
    return dict(n=int(n), base=float(b.mean()) if len(b) else float("nan"), head=float(a.mean()) if len(a) else float("nan"),
                diff=float(d), p=float(p), testable=bool(n >= MIN_SEQ), holds=bool(n >= MIN_SEQ and d > 0 and p < 0.05))


def fmt(c):
    return f"{c['base']:.3f} | {c['head']:.3f} | {c['diff']:+.3f} ({c['p']:.4g}, n = {c['n']})"


def rounded(c):
    return {k: (round(v, 5) if isinstance(v, float) and np.isfinite(v) else (None if isinstance(v, float) else v))
            for k, v in c.items()}


def main():
    parts = [pd.read_csv(p) for p in sorted(glob.glob(os.path.join(R, "P23-dynamic", "*", "P23-dynamic.csv")))]
    df = pd.concat(parts, ignore_index=True)
    dyn, sta = df[df.kind == "dynamic"], df[df.kind == "static"]
    any_base = next(b for b in BASES if b in df.model.values)
    fm_d = float(seqmean(dyn, any_base, "frac_M").mean())
    fm_s = float(seqmean(sta, any_base, "frac_M").mean())
    guard = bool(fm_s <= FLOOR_RATIO * fm_d)
    J = {"frac_M_dynamic": round(fm_d, 6), "frac_M_static": round(fm_s, 6), "label_valid": guard, "cells": {}}
    L = ["# Sixteenth pass: moving scenes, full video (generated by scripts/make_stats_p23.py; declared in LOG.md)", "",
         f"TUM RGB-D, freiburg3 camera, {dyn.scan.nunique()} sequences with moving people and {sta.scan.nunique()} static "
         f"sequences, 200 frames in temporal order, consecutive windows of {int(df.n_views.iloc[0])} frames. Unit: sequence "
         "(mean over its windows); paired sign-flip over sequences.", "",
         f"**Label validity.** Share of pixels labelled moving: {100 * fm_d:.2f}% on the dynamic sequences, "
         f"{100 * fm_s:.3f}% on the static ones (every such pixel is label noise). The moving class is "
         f"{'read' if guard else 'NOT read'} (rule: static share at most a quarter of the dynamic share).", "",
         "## Dynamic sequences", "",
         "| backbone | S vs U: native | head | head - native (p) | holds | S vs M: native | head | head - native (p) | holds | "
         "S vs U: reprojection | S vs M: reprojection |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    nA = nB = nb = 0
    for b in BASES:
        if b not in df.model.values or f"{b}_oiavisself" not in df.model.values:
            continue
        nb += 1
        A = compare(dyn, f"{b}_oiavisself", b, "auroc_SU")
        B = compare(dyn, f"{b}_oiavisself", b, "auroc_SM")
        B["holds"] = bool(B["holds"] and guard)
        nA += A["holds"]; nB += B["holds"]
        rp = {c: float(seqmean(dyn, f"{b}_reproj", c).mean()) if f"{b}_reproj" in df.model.values else float("nan")
              for c in ("auroc_SU", "auroc_SM")}
        extra = {}
        for kind, x in (("dynamic", dyn), ("static", sta)):
            for m in (b, f"{b}_reproj", f"{b}_oiavisself"):
                for c in COLS + ("score_S", "score_U", "score_M", "frac_S", "frac_U", "frac_M"):
                    if c in x and (x.model == m).any():
                        v = seqmean(x, m, c)
                        extra[f"{kind}:{m}:{c}"] = round(float(v.mean()), 5) if len(v) else None
        J["cells"][b] = dict(SU=rounded(A), SM=rounded(B), reproj={k: round(v, 5) for k, v in rp.items() if np.isfinite(v)},
                             means=extra)
        L.append(f"| {b} | {fmt(A)} | {'yes' if A['holds'] else ('no' if A['testable'] else 'n/a')} | {fmt(B)} | "
                 f"{'yes' if B['holds'] else ('no' if B['testable'] and guard else 'n/a')} | {rp['auroc_SU']:.3f} | "
                 f"{rp['auroc_SM']:.3f} |")
    L += ["", "## Reported without a rule (sequence means)", "",
          "| backbone | set | detector | S vs U | S vs M | U vs M | S vs U of the vis protocol | AbsRel S | AbsRel U | AbsRel M |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for b in J["cells"]:
        for kind in ("dynamic", "static"):
            for m, name in ((b, "native"), (f"{b}_reproj", "reprojection"), (f"{b}_oiavisself", "head")):
                vals = [J["cells"][b]["means"].get(f"{kind}:{m}:{c}") for c in COLS]
                L.append(f"| {b} | {kind} | {name} | " + " | ".join("n/a" if v is None else f"{v:.3f}" for v in vals) + " |")
    need = int(np.ceil(0.75 * nb))
    J.update(backbones=nb, holds_SU=int(nA), holds_SM=int(nB), gate23_SU=bool(nb and nA >= need),
             gate23_SM=bool(nb and guard and nB >= need))
    L += ["", f"**Gate 23, static claim under motion (S vs U): {'holds' if J['gate23_SU'] else 'does not hold'}** "
              f"({nA} of {nb} backbones; rule: three quarters).",
          f"**Gate 23, moving surfaces (S vs M): {'holds' if J['gate23_SM'] else 'does not hold'}** ({nB} of {nb} backbones)."]
    open(os.path.join(R, "P23-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p23.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
