"""Statistics of the eleventh pass (pre-registered Gate 19 in LOG.md), generated from the CSVs.

  results/P18-tum/{vggt,pi3x,pi3,da3}/P12-realocc-tum.csv   real occlusion with hole-robust labels on TUM RGB-D
                                                            (realocc_eval.py --align points --label-mode zagree)

  python scripts/make_stats_p18.py    writes results/P18-stats.md and docs/assets/p18.json"""
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_stats_p17 import BASES, R, ROOT, cell, rounded  # noqa: E402


def main():
    parts = [pd.read_csv(p) for p in sorted(glob.glob(os.path.join(R, "P18-tum", "*", "P12-realocc*.csv")))
             if not p.endswith("_summary.csv")]
    df = pd.concat(parts, ignore_index=True)
    L = ["# Eleventh pass (generated by scripts/make_stats_p18.py; pre-registered in LOG.md)", "",
         "TUM RGB-D, 12 sequences, hole-robust labels, alignment fitted on input pixels with ground-truth depth. A cell "
         "qualifies if the unobserved share averages at least 0.5% and at least 0.5 of the alignment pixels lie on the "
         "scanned surface; the claim holds if the DTU-trained label-free head beats native confidence at p < 0.05 "
         "(paired sign-flip over sequences).", "",
         "| views | backbone | scenes | ambiguous share | unobserved share | aligned on surface | qualifies | "
         "native AUROC | head AUROC | head - native (p) | claim holds |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    J = {"cells": {}}
    nq = nh = nsig = ncell = 0
    for n in sorted(df.n_views.unique()):
        x = df[df.n_views == n]
        for b in BASES:
            if b not in x.model.values or f"{b}_oiavisself" not in x.model.values:
                continue
            c = cell(x, f"{b}_oiavisself", b)
            nq += c["qualifies"]; nh += c["holds"]; ncell += 1
            nsig += bool(c["diff"] > 0 and c["p"] < 0.05)
            J["cells"][f"TUM RGB-D:{n}:{b}"] = rounded(c)
            L.append(f"| {n} | {b} | {c['n']} | {100 * c['amb']:.2f}% | {100 * c['share']:.2f}% | {c['onsurf']:.3f} | "
                     f"{'yes' if c['qualifies'] else 'no'} | {c['native']:.3f} | {c['head']:.3f} | "
                     f"{c['diff']:+.3f} ({c['p']:.4g}) | {'yes' if c['holds'] else ('no' if c['qualifies'] else 'n/a')} |")
    ok = nq >= 6 and 2 * nh >= nq
    J.update(qualifying=int(nq), holds=int(nh), significant_any_share=int(nsig), cells_total=int(ncell), gate19=bool(ok))
    L += ["", f"**Gate 19 {'passes' if ok else 'fails'}:** the claim holds in {nh} of {nq} qualifying cells "
              f"({ncell} cells scored; head above native at p < 0.05 in {nsig} without the share threshold)."]
    open(os.path.join(R, "P18-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p18.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
