"""LaTeX fragment and statistics of the provenance heads (run family P10-prov), generated from the run CSVs so that
no number is typed by hand.

  python scripts/make_tab_prov.py [--out paper/tex]     writes tab_prov.tex, results/P10-prov-stats.md and
                                                        docs/assets/prov.json

Rows per backbone: the label-free support head of the main table (no attribution; from P4-vis*, P7-vis-imc), the
provenance head trained on ground-truth per-view visibility, the label-free provenance head, and the reprojection
test with the model's own cameras (training-free attribution baseline). Columns per dataset: AUROC and CUR of the
support score (the same protocol and cells as the vis table) and the attribution columns: prov-AUROC (over every
ordered pair of views and every decided pixel, does the score rank the views that see the point above the views
that do not), the in-frame prov-AUROC (negatives restricted to views whose frame contains the point) and top-1 (on
supported pixels, the highest-scoring view sees the point). Means over scene means; the paired sign-flip tests
(provenance head against the reprojection baseline on prov-AUROC, against the conv head on AUROC) go to the stats
file."""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASETS = [("DTU", "dtu", "P4-vis"), ("CO3Dv2", "co3d", "P4-vis-co3d"), ("ETH3D", "eth3d", "P4-vis-eth3d"),
            ("Photot.", "imc", "P7-vis-imc")]
BASES = [("vggt", "VGGT-1B"), ("pi3x", "Pi3X"), ("pi3", "Pi3"), ("da3", "Depth Anything 3")]
ROWS = [("oiavisself", "support head, label-free (no attribution)"), ("reproj", "reprojection, own cameras"),
        ("oiaprov", "provenance head, GT labels"), ("oiaprovself", "\\textbf{provenance head, label-free}")]
COLS = ["auroc", "cur", "prov_auroc", "prov_auroc_inframe", "prov_top1"]


def load(tag, visrun):
    """P10 rows of a dataset plus the conv-head rows of the matching vis run (same cells)."""
    frames = []
    p = os.path.join(ROOT, "results", f"P10-prov-{tag}", f"P10-prov-{tag}.csv")
    if not os.path.exists(p):
        return None
    frames.append(pd.read_csv(p))
    q = os.path.join(ROOT, "results", visrun, f"{visrun}.csv")
    if os.path.exists(q):
        v = pd.read_csv(q)
        frames.append(v[v.model.str.endswith("_oiavisself")])
    d = pd.concat(frames, ignore_index=True)
    if "skipped" in d:
        d = d[~d.skipped.astype(bool)]
    return d.drop_duplicates(subset=["model", "scan", "seed", "radius_frac", "fill"])


def mean_cells(d, model):
    x = d[d.model == model]
    if x.empty:
        return None
    g = x.groupby("scan")[[c for c in COLS if c in x]].mean().mean()
    return {c: (float(g[c]) if c in g and np.isfinite(g[c]) else None) for c in COLS}


def fmt(v, nd=3):
    return "--" if v is None else f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "paper", "tex"))
    a = ap.parse_args()
    data = {name: load(tag, run) for name, tag, run in DATASETS}
    present = [n for n in data if data[n] is not None]
    if not present:
        print("no P10-prov results yet"); return
    lines, stats, J = [], ["# Provenance heads (generated by scripts/make_tab_prov.py from results/P10-prov-*)", ""], {}
    for base, blabel in BASES:
        rows = []
        for suf, label in ROWS:
            model = f"{base}_{suf}"
            cells = []
            any_ = False
            for n in present:
                m = mean_cells(data[n], model)
                if m is None:
                    cells.append(" & ".join(["--"] * 5)); continue
                any_ = True
                J.setdefault(n, {}).setdefault(base, {})[suf] = m
                cells.append(" & ".join(fmt(m[c]) for c in COLS))
            if any_:
                rows.append(f"{label} & " + " & ".join(cells) + r" \\")
        if rows:
            lines.append(r"\multicolumn{%d}{l}{\emph{%s}} \\" % (1 + 5 * len(present), blabel))
            lines += rows
        # paired tests per dataset
        for n in present:
            d = data[n]
            for a_, b_, col in ((f"{base}_oiaprovself", f"{base}_reproj", "prov_auroc"), (f"{base}_oiaprov", f"{base}_reproj", "prov_auroc"),
                                (f"{base}_oiaprovself", f"{base}_reproj", "prov_top1"),
                                (f"{base}_oiaprovself", f"{base}_oiavisself", "auroc"), (f"{base}_oiaprovself", f"{base}_oiavisself", "cur"),
                                (f"{base}_oiaprovself", f"{base}_oiaprov", "prov_auroc")):
                if a_ in d.model.values and b_ in d.model.values and col in d:
                    dd = d.dropna(subset=[col])
                    try:
                        diff, p = H.paired_permutation(dd, col, a_, b_)
                    except Exception as e:                      # fewer than two common scenes
                        diff, p = float("nan"), float("nan")
                    stats.append(f"| {n} | {a_} vs {b_} | {col} | {diff:+.4f} | {p:.4g} |")
                    J.setdefault(n, {}).setdefault(base, {}).setdefault("tests", {})[f"{a_}:{b_}:{col}"] = [round(float(diff), 4), round(float(p), 5)]
    head = "detector & " + " & ".join(f"\\multicolumn{{5}}{{c}}{{{n}}}" for n in present) + r" \\"
    sub = " & " + " & ".join(r"\auroc & \cur & prov-\auroc & in-frame & top-1" for _ in present) + r" \\"
    out = os.path.join(a.out, "tab_prov.tex")
    open(out, "w", encoding="utf-8", newline="\n").write(
        "% generated by scripts/make_tab_prov.py from results/P10-prov-* (+ the conv-head rows of P4-vis*, P7-vis-imc)\n"
        + "\\begin{tabular}{l*{%d}{ccccc}}\n\\toprule\n" % len(present) + head + "\n" + sub + "\n\\midrule\n"
        + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
    print("->", out, len(lines), "rows; datasets", present)
    sp = os.path.join(ROOT, "results", "P10-prov-stats.md")
    open(sp, "w", encoding="utf-8", newline="\n").write("\n".join(
        stats[:2] + ["| dataset | pair | column | mean paired difference (a - b) | p (sign-flip, 20000) |", "|---|---|---|---|---|"] + stats[2:]) + "\n")
    print("->", sp, len(stats) - 2, "tests")
    jp = os.path.join(ROOT, "docs", "assets", "prov.json")
    json.dump(J, open(jp, "w", encoding="utf-8"), indent=1)
    print("->", jp)


if __name__ == "__main__":
    main()
