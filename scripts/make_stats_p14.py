"""Statistics of the seventh pass (pre-registered Gate 12 in EXPERIMENTS.md), generated from the run CSVs.

  validity   results/P14-realocc/holes*/P14-holes-*.csv   hole rate of the observed test per dataset and view count
  DTU        results/P12-realocc/P12-realocc.csv           18 benchmark scans, four backbones (Gate 10 rows)
  DTU test   results/P14-realocc/dext_{a,b}/P12-realocc.csv 22 test scans, four backbones
  ETH3D      results/P12-realocc/P12-realocc-eth3d.csv + results/P14-realocc/eth/P12-realocc-eth3d.csv
  CO3Dv2     results/P14-realocc/co3d_{a,b}/P12-realocc-co3d.csv

  python scripts/make_stats_p14.py    writes results/P14-stats.md and docs/assets/p14.json"""
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hallu3d as H  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
BASES = ["vggt", "pi3x", "pi3", "da3"]
HOLE_MAX = 0.10
ONSURF_MIN = 0.5
SETS = [  # name, gate, row CSVs, hole CSV
    ("DTU benchmark", 10, ["P12-realocc/P12-realocc.csv"], "P14-realocc/holes/P14-holes-dtu.csv"),
    ("ETH3D", "10/12", ["P12-realocc/P12-realocc-eth3d.csv", "P14-realocc/eth/P12-realocc-eth3d.csv"],
     "P14-realocc/holes/P14-holes-eth3d.csv"),
    ("DTU test", 12, ["P14-realocc/dext_a/P12-realocc.csv", "P14-realocc/dext_b/P12-realocc.csv"],
     "P14-realocc/holes_dext/P14-holes-dtu.csv"),
    ("CO3Dv2", 12, ["P14-realocc/co3d_a/P12-realocc-co3d.csv", "P14-realocc/co3d_b/P12-realocc-co3d.csv"],
     "P14-realocc/holes/P14-holes-co3d.csv"),
]


def main():
    L = ["# Seventh pass (generated by scripts/make_stats_p14.py)", "",
         f"Gate 12 rule per (dataset, views, backbone): valid if the mean hole rate is at most {HOLE_MAX:.2f}; "
         "qualifies if valid and the unobserved share averages at least 0.5%; the claim holds if the label-free head beats "
         "native confidence at p < 0.05 (paired sign-flip over scenes).", ""]
    J = {"cells": {}}
    for name, gate, csvs, hole_csv in SETS:
        parts = [pd.read_csv(os.path.join(R, c)) for c in csvs if os.path.exists(os.path.join(R, c))]
        if not parts:
            L += [f"## {name}: no rows", ""]; continue
        rd = pd.concat(parts, ignore_index=True)
        rd["scan"] = rd["scan"].astype(str)
        hp = os.path.join(R, hole_csv)
        hd = pd.read_csv(hp) if os.path.exists(hp) else None
        L += [f"## {name} (Gate {gate})", "",
              "| views | backbone | scenes | hole rate | aligned on surface | valid | unobserved share | qualifies | native AUROC | reprojection AUROC | head AUROC | head - native (p) | claim holds |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for n in sorted(rd.n_views.unique()):
            x = rd[rd.n_views == n]
            hr = float(hd[hd.n_views == n].groupby("scan").hole_rate.mean().mean()) if hd is not None else float("nan")
            valid = bool(hr <= HOLE_MAX) if hd is not None else None
            # Gate 12 amendment: a cell aligned on pixels must also show that the alignment worked
            al = float(x.groupby("scan").onsurf_valid.mean().mean()) if "onsurf_valid" in x.columns and                 (x.get("align") == "points").all() else float("nan")
            if al == al and valid is not None:
                valid = valid and al >= ONSURF_MIN
            for b in BASES:
                if b not in x.model.values or f"{b}_oiavisself" not in x.model.values:
                    continue
                y = x[x.model == b]
                fr = float(y.groupby("scan").frac_unobs.mean().mean())
                an = float(y.groupby("scan").auroc_obs_unobs.mean().mean())
                ar = float(x[x.model == f"{b}_reproj"].groupby("scan").auroc_obs_unobs.mean().mean()) \
                    if f"{b}_reproj" in x.model.values else float("nan")
                ah = float(x[x.model == f"{b}_oiavisself"].groupby("scan").auroc_obs_unobs.mean().mean())
                t = H.paired_permutation(x, "auroc_obs_unobs", f"{b}_oiavisself", b)
                q = bool(valid) and fr >= 0.005
                holds = bool(q and t[0] > 0 and t[1] < 0.05)
                J["cells"][f"{name}:{n}:{b}"] = dict(gate=gate, hole_rate=round(hr, 4), onsurf=round(al, 4), valid=valid, share=round(fr, 5),
                                                     qualifies=q, native=round(an, 4), reproj=round(ar, 4), head=round(ah, 4),
                                                     diff=[round(t[0], 4), round(t[1], 5)], holds=holds,
                                                     n_scenes=int(y.scan.nunique()))
                L.append(f"| {n} | {b} | {y.scan.nunique()} | {hr:.3f} | {al:.3f} | {'yes' if valid else 'no'} | {100 * fr:.2f}% | "
                         f"{'yes' if q else 'no'} | {an:.3f} | {ar:.3f} | {ah:.3f} | {t[0]:+.3f} ({t[1]:.4g}) | "
                         f"{'yes' if holds else ('no' if q else 'n/a')} |")
        L.append("")
    cells = J["cells"].values()
    qual = [v for v in cells if v["qualifies"]]
    J["total"] = dict(qualifying=len(qual), holds=sum(v["holds"] for v in qual),
                      invalid=sum(1 for v in cells if v["valid"] is False))
    L.append(f"**All real datasets (Gates 10 and 12 together):** {len(qual)} qualifying cells; the claim holds in "
             f"{J['total']['holds']}. Cells not valid by the hole-rate check: {J['total']['invalid']}.")
    open(os.path.join(R, "P14-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(ROOT, "docs", "assets", "p14.json"), "w", encoding="utf-8"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
