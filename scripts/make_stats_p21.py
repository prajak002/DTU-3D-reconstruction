"""Fourteenth pass (pre-registered in LOG.md): tables for the causal test of the support direction
(results/P21-causal) and the foreign-view test, Gate 22 (results/P21-foreign). Writes results/P21-stats.md."""
import os

import numpy as np
import pandas as pd


def signflip(x, n=20000, seed=0):
    x = np.asarray(x, float)
    s = np.random.default_rng(seed).choice([-1, 1], size=(n, len(x)))
    return float(x.mean()), float((np.abs((s * x).mean(1)) >= abs(x.mean()) - 1e-12).mean())


def main():
    L = ["# Fourteenth pass (generated by scripts/make_stats_p21.py; pre-registered in LOG.md)", "",
         "## A. Causal test of the support direction (18 DTU benchmark scans, 5 views; exploratory, no pass rule)", "",
         "One direction per hooked layer (mean supported token minus mean single-view token, fitted on 12 training scans). "
         "`ablate`: its component set to the capture mean. `rand`: the same edit along a random direction (mean of three). "
         "`plus` / `minus`: every patch token shifted by one inter-class distance. p: paired sign-flip over scans, ablate against rand.", ""]
    cols = ["auroc_head", "auroc_native", "absrel_S", "absrel_U", "conf_S", "conf_U", "dchange_S", "dchange_U"]
    for b in ("vggt", "pi3x", "pi3"):
        p = os.path.join("results", "P21-causal", f"P21-causal-{b}.csv")
        if not os.path.exists(p):
            continue
        d = pd.read_csv(p)
        d["cond"] = d["mode"].str.replace(r"rand\d", "rand", regex=True)
        g = d.groupby(["scan", "cond"]).mean(numeric_only=True).reset_index()
        t = g.groupby("cond")[cols].mean()
        L += [f"### {b} ({g.scan.nunique()} scans)", "",
              "| condition | head AUROC | native AUROC | AbsRel supported | AbsRel single-view | native conf supported | native conf single-view | depth change supported | depth change single-view |",
              "|---|---|---|---|---|---|---|---|---|"]
        for c in ("none", "ablate", "rand", "plus", "minus"):
            r = t.loc[c]
            L.append(f"| {c} | {r.auroc_head:.3f} | {r.auroc_native:.3f} | {r.absrel_S:.4f} | {r.absrel_U:.4f} | {r.conf_S:.3f} | {r.conf_U:.3f} | {r.dchange_S:.4f} | {r.dchange_U:.4f} |")
        pv = g.pivot(index="scan", columns="cond")
        tests = [f"{c}: {m:+.4f} (p = {q:.5f})" for c in ("auroc_head", "auroc_native", "absrel_S", "absrel_U")
                 for m, q in [signflip(pv[c]["ablate"] - pv[c]["rand"])]]
        L += ["", "ablate minus rand: " + "; ".join(tests), ""]
    L += ["## C. Variance-matched control for the causal test (declared in LOG.md before the run)", "",
          "`pc0` to `pc2`: the same edit along the three highest-variance principal directions of the patch tokens after the support "
          "direction is projected out. p: paired sign-flip over scans, ablate against that direction.", ""]
    ok = tot = 0
    for b in ("vggt", "pi3x", "pi3"):
        p = os.path.join("results", "P21b-causal", f"P21-causal-{b}.csv")
        if not os.path.exists(p):
            continue
        d = pd.read_csv(p)
        d["cond"] = d["mode"].str.replace(r"rand\d", "rand", regex=True)
        g = d.groupby(["scan", "cond"]).mean(numeric_only=True).reset_index()
        t = g.groupby("cond")[cols].mean()
        pv = g.pivot(index="scan", columns="cond")
        v = pd.read_csv(os.path.join("results", "P21b-causal", f"P21-causal-{b}-variance.csv"))
        L += [f"### {b}", "", "token variance per layer, support direction / pc0 / pc1 / pc2: "
              + "; ".join(f"{r.var_support:.1f} / {r.var_pc0:.1f} / {r.var_pc1:.1f} / {r.var_pc2:.1f}" for r in v.itertuples()), "",
              "| condition | head AUROC | native AUROC | AbsRel supported | AbsRel single-view | ablate - this: head AUROC (p) | AbsRel single-view (p) |",
              "|---|---|---|---|---|---|---|"]
        for c in ("none", "ablate", "rand", "pc0", "pc1", "pc2"):
            r = t.loc[c]
            extra = "| | |"
            if c.startswith("pc"):
                m, q = signflip(pv["auroc_head"]["ablate"] - pv["auroc_head"][c])
                m2, q2 = signflip(pv["absrel_U"]["ablate"] - pv["absrel_U"][c])
                tot += 1
                ok += int(m < 0 and q < 0.05)
                extra = f"| {m:+.3f} ({q:.5f}) | {m2:+.4f} ({q2:.5f}) |"
            L.append(f"| {c} | {r.auroc_head:.3f} | {r.auroc_native:.3f} | {r.absrel_S:.4f} | {r.absrel_U:.4f} {extra}")
        L.append("")
    L += [f"**Stated criterion:** ablating the support direction lowers the head's AUROC more than ablating the principal direction, "
          f"p < 0.05, in {ok} of {tot} comparisons (needed: all).", ""]
    L += ["## B. Foreign-view test (Gate 22)", "",
          "K - 1 views of a DTU benchmark scan plus one view of another scan (`scan`) or Gaussian noise (`noise`); 18 scans, seeds 0 to 2. "
          "`sep`: share of genuine views whose mean score is above the foreign view's (chance 0.5). p: paired sign-flip over the 54 captures, head against native.", "",
          "| setting | K | backbone | sep native | sep reprojection | sep head | top-1 native | top-1 reprojection | top-1 head | head - native sep (p) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    held = n = 0
    for kind in ("scan", "noise"):
        for K in (5, 10):
            for b in ("vggt", "pi3x", "pi3", "da3"):
                p = os.path.join("results", "P21-foreign", f"P21-foreign-{b}.csv")
                if not os.path.exists(p):
                    continue
                d = pd.read_csv(p)
                d = d[(d.kind == kind) & (d.n_views == K)]
                s = d.pivot_table(index=["scan", "seed"], columns="model", values="sep")
                t = d.groupby("model")["top1"].mean()
                m, q = signflip(s[f"{b}_oiavisself"] - s[b])
                if kind == "scan" and K == 5:
                    n += 1
                    held += int(m > 0 and q < 0.05)
                L.append(f"| {kind} | {K} | {b} | {s[b].mean():.3f} | {s[f'{b}_reproj'].mean():.3f} | {s[f'{b}_oiavisself'].mean():.3f} | "
                         f"{t[b]:.3f} | {t[f'{b}_reproj']:.3f} | {t[f'{b}_oiavisself']:.3f} | {m:+.3f} ({q:.4f}) |")
    L += ["", f"**Gate 22 {'holds' if 4 * held >= 3 * n and n == 4 else 'fails'}:** at K = 5 the head separates the foreign view better than native "
              f"confidence at p < 0.05 on {held} of {n} backbones (needed: three of four)."]
    open(os.path.join("results", "P21-stats.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("\n".join(L[-3:]))


if __name__ == "__main__":
    main()
